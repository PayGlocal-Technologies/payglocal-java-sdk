package com.glocal;

import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;

import javax.crypto.Mac;
import javax.crypto.spec.SecretKeySpec;
import java.nio.charset.StandardCharsets;
import java.security.InvalidKeyException;
import java.security.NoSuchAlgorithmException;
import java.util.Base64;

// API Key + HMAC-SHA256 authentication, used by the Partner Merchant Onboarding APIs.
// Each request carries two headers:
// x-gl-auth   -> your static API Key (from the PayGlocal Partner Dashboard)
// x-gl-digest -> Base64(HmacSHA256(signingInput, API_SECRET)), generated by HmacDigest.generate
// This class only generates the digest. Adding the headers to the request is left to the caller.
public class HmacDigest {

    private static final Logger logger = LogManager.getLogger(HmacDigest.class.getName());

    private static final String HMAC_ALGORITHM = "HmacSHA256";
    private static final String GET_METHOD = "GET";

    // function to select the input that has to be signed
    // httpMethod : HTTP method of the request (GET, POST, PUT)
    // requestUri : request URI path, including the query string if present (no host or scheme)
    //              e.g. /gcc/v2/partner/merchant/onboard/business-category
    // payload : exact raw request body (json stringified), as sent on the wire
    // GET -> request URI path (including query string if present)
    // POST / PUT -> exact raw request body
    public static String getSigningInput(String httpMethod, String requestUri, String payload) {
        if (GET_METHOD.equalsIgnoreCase(httpMethod)) {
            return requestUri;
        }
        return payload;
    }

    // function to create the digest for the x-gl-digest header
    // httpMethod : HTTP method of the request (GET, POST, PUT)
    // requestUri : request URI path, including the query string if present (used for GET)
    // payload : exact raw request body (json stringified), used for POST / PUT. Compute the digest over the
    //           same string you send as the body, any difference in whitespace or field order fails with 401
    // apiSecret : API Secret of the partner (Downloaded from the PayGlocal Partner Dashboard), never the API Key
    public static String generate(String httpMethod, String requestUri, String payload, String apiSecret) {
        if (apiSecret == null || apiSecret.isEmpty()) {
            logger.error("Partner API secret is null.");
            return null;
        }

        String signingInput = getSigningInput(httpMethod, requestUri, payload);
        if (signingInput == null) {
            logger.error("Signing input is null. Pass requestUri for GET and payload for POST / PUT.");
            return null;
        }

        try {
            // Calculate the HMAC of the signing input using the API Secret as the key
            Mac mac = Mac.getInstance(HMAC_ALGORITHM);
            mac.init(new SecretKeySpec(apiSecret.getBytes(StandardCharsets.UTF_8), HMAC_ALGORITHM));
            byte[] hmacOfSigningInput = mac.doFinal(signingInput.getBytes(StandardCharsets.UTF_8));

            logger.info("Created {} digest for {} request", HMAC_ALGORITHM, httpMethod);
            // Converted the HMAC to base64 encoder
            return Base64.getEncoder().encodeToString(hmacOfSigningInput);
        } catch (NoSuchAlgorithmException | InvalidKeyException e) {
            logger.error("Unable to create HMAC digest for request", e);
            return null;
        }
    }
}
